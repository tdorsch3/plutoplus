#!/usr/bin/env python3
"""Refresh data/snapshot.js, the offline copy of the tracker data bundled with the app.

Runs the same Google Sheets queries as the in-app "Sync" button (listed in
js/queries.js) and saves the raw responses. Standard library only:

    python3 tools/update_snapshot.py
"""
import datetime
import json
import pathlib
import sys
import urllib.parse
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent


def load_source():
    text = (ROOT / "js" / "queries.js").read_text(encoding="utf-8")
    start = text.index("=", text.index("window.TRACKER_SOURCE")) + 1
    return json.loads(text[start:text.rindex(";")])


def fetch(sheet_id, sheet, cell_range):
    params = urllib.parse.urlencode({
        "tqx": "out:json",
        "headers": "0",
        "sheet": sheet,
        "range": cell_range,
    })
    url = f"https://docs.google.com/spreadsheets/d/{sheet_id}/gviz/tq?{params}"
    with urllib.request.urlopen(url, timeout=30) as resp:
        body = resp.read().decode("utf-8")
    # Body looks like: /*O_o*/\ngoogle.visualization.Query.setResponse({...});
    data = json.loads(body[body.index("(") + 1:body.rindex(")")])
    if data.get("status") != "ok":
        errors = data.get("errors") or [{}]
        raise RuntimeError(f"{sheet}!{cell_range}: {errors[0].get('detailed_message', data.get('status'))}")
    return data


def main():
    source = load_source()
    responses = {}
    for name, q in source["queries"].items():
        responses[name] = fetch(source["sheetId"], q["sheet"], q["range"])
        print(f"  {name:13s} {q['sheet']}!{q['range']}: {len(responses[name]['table']['rows'])} rows")
    snapshot = {
        "fetchedAt": datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds"),
        "responses": responses,
    }
    out = ROOT / "data" / "snapshot.js"
    out.write_text(
        "// Generated by tools/update_snapshot.py. Bundled fallback data so the app works offline.\n"
        f"window.TRACKER_SNAPSHOT = {json.dumps(snapshot, ensure_ascii=False, separators=(',', ':'))};\n",
        encoding="utf-8",
    )
    print(f"Wrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    try:
        main()
    except Exception as exc:  # noqa: BLE001 - report any failure plainly
        sys.exit(f"Snapshot update failed: {exc}")
